import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  progressSchema,
  calculateProgress,
  formatPercent,
  statusInfo,
} from "../src/minishop-web/src/development-progress/model.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Usage: node scripts/update-progress.mjs [--check]");
const data = progressSchema.parse(
  JSON.parse(
    await fs.readFile(
      path.join(root, "progress/development-progress.json"),
      "utf8",
    ),
  ),
);
// Evidence must point to reviewable repository files. A file's existence NEVER changes a task status.
const references = new Set([
  ...data.evidence.flatMap((e) => e.paths),
  ...data.milestones.flatMap((m) => m.tasks.flatMap((t) => t.sources)),
]);
for (const source of references) await fs.access(path.join(root, source));
const progress = calculateProgress(data);
const label = (status) => statusInfo[status].label;
const safe = (value) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const lines = [
  "# MiniShop POS development progress",
  "",
  "<!-- Generated by scripts/update-progress.mjs. Edit progress/development-progress.json; do not edit this report. -->",
  "",
  `Last reviewed: **${data.updatedAt} (Asia/Manila)**. Baseline source revision: \`${data.baselineRevision}\`; this snapshot also covers the reviewed local changes.`,
  "",
  `Current phase: **${data.phase}**.`,
  "",
  `**Overall: ${formatPercent(progress.overall)} · Functional development: ${formatPercent(progress.functional)} · Production readiness: ${formatPercent(progress.readiness)} · Cloud preparation: ${formatPercent(progress.preparation)}**`,
  "",
  `${progress.completedMilestones}/${progress.milestones.length} milestones and ${progress.completedTasks}/${progress.tasks.length} acceptance tasks are complete and verified. ${progress.pendingTasks} tasks remain; ${progress.blockers.length} are externally blocked. **${progress.openGates.length} release gates remain open. Production rollout is not approved.**`,
  "",
  data.assessmentNote,
  "",
  "## How the percentages are calculated",
  "",
  "Task credit: " +
    Object.values(statusInfo)
      .map((s) => `${s.classification} = ${s.credit * 100}%`)
      .join("; ") +
    ".",
  "",
  "Each task has 1 acceptance point unless explicitly weighted otherwise. Milestone completion = earned task points / available task points. Overall = sum(milestone completion × category weight). Intermediate calculations are not rounded; display values round once to one decimal place.",
  "",
  `Functional development normalizes the product-feature categories (${progress.weights.functional}% of overall weight). Production readiness normalizes testing, hardware/LAN and security (${progress.weights.readiness}%). Cloud preparation uses the remaining ${progress.weights.preparation}%. These are separate track scores, not additional percentages to add together. A high aggregate score never overrides an unverified release gate.`,
  "",
  "| Milestone | Track | Weight | Completion | Overall contribution | Status |",
  "| --- | --- | ---: | ---: | ---: | --- |",
  ...progress.milestones.map(
    (m) =>
      `| ${m.title} | ${m.track} | ${m.weight}% | ${formatPercent(m.completion)} | ${formatPercent(m.contribution)} | ${label(m.status)} |`,
  ),
  "",
  "## Testing evidence",
  "",
  "These are explicitly reviewed historical run results, not a live test monitor. Regenerating this report runs no tests and grants no completion credit.",
  "",
  "| Suite | Last run | Passed | Failed | Skipped | Status | Command |",
  "| --- | --- | ---: | ---: | ---: | --- | --- |",
  ...data.testRuns.map(
    (t) =>
      `| ${t.title} | ${t.verifiedAt} | ${t.passed} | ${t.failed} | ${t.skipped} | ${t.status} | \`${t.command}\` |`,
  ),
  "",
  "## Completed features and outstanding work",
  "",
];
for (const milestone of progress.milestones) {
  lines.push(
    `### ${milestone.title} — ${formatPercent(milestone.completion)}`,
    "",
    milestone.summary,
    "",
    "| Feature | Classification | Evidence / remaining acceptance |",
    "| --- | --- | --- |",
  );
  for (const task of milestone.tasks)
    lines.push(
      `| ${safe(task.title)}${task.releaseGate ? " **[release gate]**" : ""} | ${statusInfo[task.status].classification} | ${safe(task.detail)} ${task.evidenceIds.length ? `Evidence: ${task.evidenceIds.map((e) => `\`${e}\``).join(", ")}.` : "No completion evidence."}${task.next ? ` **Next:** ${safe(task.next)}` : ""} |`,
    );
  lines.push("");
}
lines.push(
  "## Known blockers",
  "",
  ...progress.blockers.map((t) => `- **${t.title}:** ${t.detail} ${t.next}`),
  "",
  "## Known issues",
  "",
  ...data.knownIssues.map((i) => `- **${i.title}:** ${i.detail}`),
  "",
  "## Next priorities",
  "",
  ...data.priorities.map((p, i) => {
    const t = progress.tasks.find((t) => t.id === p.taskId);
    return `${i + 1}. **${t.title}.** ${p.reason} Acceptance: ${p.acceptance}${p.dependsOn.length ? ` Depends on: ${p.dependsOn.map((id) => progress.tasks.find((t) => t.id === id).title).join(", ")}.` : ""}`;
  }),
  "",
  "## Evidence register",
  "",
);
for (const e of data.evidence)
  lines.push(
    `### ${e.id} — ${e.title}`,
    "",
    `${e.method} verification · ${e.verifiedAt}. ${e.result}`,
    "",
    ...e.paths.map((p) => `- [${p}](${p})`),
    "",
  );
lines.push(
  "## Future scope excluded from this initial-release score",
  "",
  ...data.futureScope.map((s) => `- ${s}`),
  "",
  "## Maintenance",
  "",
  "After a milestone, inspect the relevant implementation and execute its acceptance checks. Record the evidence/date and manually review task classifications in `progress/development-progress.json`. Then run:",
  "",
  "```powershell",
  "node scripts/update-progress.mjs",
  "node scripts/update-progress.mjs --check",
  "```",
  "",
  "The generator validates weights, evidence references and source paths, recalculates all metrics and regenerates this report and `docs/DEVELOPMENT_ROADMAP.md`. It does not infer completion from files, test counts, commits or successful commands. See [the maintenance guide](docs/PROGRESS_MAINTENANCE.md). Rebuild/redeploy the API after reviewing JSON changes; the private progress file is copied to its output/publish directory.",
  "",
  "Open `/admin/development-progress` as Owner. The server endpoint `/api/admin/development-progress` denies cashiers and anonymous clients. No API editing endpoint or GitHub push is part of this process.",
  "",
);

const roadmap = [
  "# MiniShop POS remaining development roadmap",
  "",
  "<!-- Generated by scripts/update-progress.mjs from progress/development-progress.json. -->",
  "",
  `Last reviewed: ${data.updatedAt} (Asia/Manila). Phase: ${data.phase}.`,
  "",
  "Priorities below are ordered by counter-operation impact and dependencies. External acceptance is required where marked; documentation alone cannot close a release gate.",
  "",
];
for (const [i, p] of data.priorities.entries()) {
  const task = progress.tasks.find((t) => t.id === p.taskId);
  roadmap.push(
    `## ${i + 1}. ${task.title}`,
    "",
    `Status: **${label(task.status)}**${task.releaseGate ? " · Release gate" : ""}.`,
    "",
    `Why: ${p.reason}`,
    "",
    `Acceptance: ${p.acceptance}`,
    "",
    `Dependencies: ${p.dependsOn.length ? p.dependsOn.map((id) => progress.tasks.find((t) => t.id === id).title).join("; ") : "None; can start independently."}.`,
    "",
    `Reviewed source: ${task.sources.map((s) => `[${s}](../${s})`).join(", ")}.`,
    "",
  );
}
const prioritized = new Set(data.priorities.map((p) => p.taskId));
roadmap.push(
  "## Remaining verification and capacity work",
  "",
  ...progress.tasks
    .filter((t) => t.status !== "verified" && !prioritized.has(t.id))
    .map((t) => `- **${t.title} (${label(t.status)}):** ${t.next}`),
  "",
  "## Later optional features",
  "",
  ...data.futureScope.map((s) => `- ${s}`),
  "",
  "## Release decision",
  "",
  `There are ${progress.openGates.length} open gates. The owner should accept a rollout only after actual device/network/security/recovery/commercial checks are recorded and blocking findings are resolved. A percentage alone cannot authorize deployment. See [progress](../PROGRESS.md) and [maintenance](PROGRESS_MAINTENANCE.md).`,
  "",
);
const outputs = new Map([
  ["PROGRESS.md", lines.join("\n")],
  ["docs/DEVELOPMENT_ROADMAP.md", roadmap.join("\n")],
  [
    "docs/PROGRESS.md",
    "# Development progress\n\n<!-- Generated navigation; the reviewed JSON is the source of truth. -->\n\nSee [the current weighted progress report](../PROGRESS.md), [the remaining roadmap](DEVELOPMENT_ROADMAP.md) and [the maintenance process](PROGRESS_MAINTENANCE.md).\n\nThe original implementation checklist is preserved as [historical implementation notes](IMPLEMENTATION_HISTORY.md). Completed implementation milestones did not mean production acceptance was complete.\n",
  ],
]);
let stale = false;
for (const [target, content] of outputs) {
  const file = path.join(root, target);
  if (check) {
    const actual = await fs.readFile(file, "utf8").catch(() => null);
    if (actual?.replaceAll("\r\n", "\n") !== content) {
      console.error(`Out of date: ${target}`);
      stale = true;
    }
  } else await fs.writeFile(file, content, "utf8");
}
if (stale) process.exitCode = 1;
else
  console.log(
    `${check ? "Progress reports match" : "Progress reports generated"}: overall ${formatPercent(progress.overall)}, functional ${formatPercent(progress.functional)}, readiness ${formatPercent(progress.readiness)}; ${progress.pendingTasks} pending tasks.`,
  );
